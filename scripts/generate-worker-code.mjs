/**
 * Regenerates src/lib/ffmpegWorkerCode.ts.
 *
 * The @ffmpeg/ffmpeg class worker normally lives in a separate file, which
 * breaks when the app must be self-contained. This script bundles the worker
 * into a single classic script and appends a prelude that converts core
 * bytes (sent via postMessage) into worker-local blob URLs — page-created
 * blob URLs are not fetchable from workers in opaque origins (e.g. sandboxed
 * iframes), so the worker mints its own.
 *
 * Run after upgrading @ffmpeg/ffmpeg:  npm run worker:generate
 */
import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";

const OUT = "src/lib/ffmpegWorkerCode.ts";
const TMP = "node_modules/.ffworker-bundle.js";

await build({
  entryPoints: ["node_modules/@ffmpeg/ffmpeg/dist/esm/worker.js"],
  bundle: true,
  format: "iife",
  minify: true,
  outfile: TMP,
});

const prelude = `
;(function(){
  var orig = self.onmessage;
  self.onmessage = function(e){
    var m = e.data;
    if (m && m.type === 'LOAD' && m.data && m.data.coreText) {
      var coreURL = URL.createObjectURL(new Blob([m.data.coreText], {type:'text/javascript'}));
      var wasmURL = URL.createObjectURL(new Blob([m.data.wasmBytes], {type:'application/wasm'}));
      orig({ data: { id: m.id, type: 'LOAD', data: { coreURL: coreURL, wasmURL: wasmURL } } });
    } else { orig(e); }
  };
})();`;

const code = readFileSync(TMP, "utf8") + prelude;
writeFileSync(
  OUT,
  "// Bundled @ffmpeg/ffmpeg worker (classic script, self-contained).\n" +
    "// Generated by scripts/generate-worker-code.mjs — do not edit by hand.\n" +
    "export const FFMPEG_WORKER_CODE: string = " + JSON.stringify(code) + ";\n"
);
console.log(`Wrote ${OUT} (${code.length} bytes)`);
